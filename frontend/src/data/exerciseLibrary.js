// Recherche fuzzy dans la bibliothèque
export function searchExercises(query) {
  if (!query || query.length < 2) return []
  const q = query.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
  return EXERCISE_LIBRARY.filter(ex => {
    const name = ex.name.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
    const nameEn = ex.nameEn.toLowerCase()
    const muscles = ex.muscles.join(' ').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
    return name.includes(q) || nameEn.includes(q) || muscles.includes(q)
  }).slice(0, 8)
}
